# ===========================================================
#  튜플 (tuple): 여러 객체를 순서가 있는 컬렉션으로 묶어 저장하는 변경 불가능한 자료형
#  튜플의 특징
#  1. (  ) -> 리스트와의 차이점
#  2. ( immutable )
#  3. ( 인덱싱, 슬라이싱 가능 )
#  4. ( 중복가능 )
# ===========================================================

# 튜플 생성
a = ()
b = tuple()
print(type(a), type(b))

t = 1, 3.14, True, "Hello", [1, 2, 3], (4, 5, 6)
print(t, type(t))

