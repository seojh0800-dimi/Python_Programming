# ===========================================================
# 1. 튜플은 immutable하다. (변경 불가능)
# ===========================================================
# t[0] = 10                         # __setitem__() 메소드가 없기 때문에 에러 발생
# tuple.__setitem__(t, 0, 10)       # __setitem__() 메소드가 없기 때문에 에러 발생
# list.__setitem__                  # 리스트는 __setitem__() 메소드가 있기 때문에 가능

t = (1, [2,3])
t[1].append(4)
print(t)

